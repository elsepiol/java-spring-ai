package dojo.jpa.l1.mapping;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

import dojo.jpa.support.JpaKataTest;
import jakarta.persistence.EntityManager;
import org.hibernate.Hibernate;
import org.junit.jupiter.api.Tag;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.dao.DataIntegrityViolationException;
import org.springframework.jdbc.core.JdbcTemplate;

@Tag("jpa")
@Tag("L1")
class MappingTest extends JpaKataTest {

	@Autowired
	CustomerRepository customers;

	@Autowired
	PurchaseOrderRepository orders;

	@Autowired
	EntityManager em;

	@Autowired
	JdbcTemplate jdbc;

	@Test
	void savesAndLoadsACustomer() {
		Customer ann = customers.save(new Customer("Ann Lee", "ann@example.com", Tier.STANDARD));
		assertThat(ann.getId()).as("generated by the database").isNotNull();
		em.flush();
		em.clear(); // forget everything: the next read must come from the database
		Customer loaded = customers.findByEmail("ann@example.com").orElseThrow();
		assertThat(loaded.getFullName()).isEqualTo("Ann Lee");
		assertThat(loaded).isNotSameAs(ann);
	}

	@Test
	void theTierIsStoredByName() {
		customers.save(new Customer("Bob", "bob@example.com", Tier.GOLD));
		em.flush();
		assertThat(jdbc.queryForObject("SELECT tier FROM jpa_customer WHERE email = 'bob@example.com'", String.class)).isEqualTo("GOLD");
	}

	@Test
	void changesToManagedEntitiesAreSavedWithoutCallingSave() {
		Customer cat = customers.save(new Customer("Cat", "cat@example.com", Tier.STANDARD));
		em.flush();
		cat.upgrade(); // no save() call: dirty checking writes it at flush/commit
		em.flush();
		assertThat(jdbc.queryForObject("SELECT tier FROM jpa_customer WHERE id = ?", String.class, cat.getId())).isEqualTo("GOLD");
	}

	@Test
	void anOrderReferencesItsCustomerLazily() {
		Customer dan = customers.save(new Customer("Dan", "dan@example.com", Tier.STANDARD));
		PurchaseOrder order = orders.save(new PurchaseOrder(dan, 4200));
		em.flush();
		em.clear();
		PurchaseOrder loaded = orders.findById(order.getId()).orElseThrow();
		assertThat(Hibernate.isInitialized(loaded.getCustomer())).as("customer not loaded yet").isFalse();
		assertThat(loaded.getCustomer().getEmail()).isEqualTo("dan@example.com"); // loaded now, on first use
		assertThat(jdbc.queryForObject("SELECT customer_id FROM jpa_purchase_order WHERE id = ?", Long.class, order.getId())).isEqualTo(dan.getId());
	}

	@Test
	void theDatabaseEnforcesUniqueEmails() {
		customers.save(new Customer("Eve", "eve@example.com", Tier.STANDARD));
		// IDENTITY ids: Hibernate must INSERT at save() to learn the id, so the violation surfaces right here,
		// translated by the repository into Spring's DataIntegrityViolationException
		assertThatThrownBy(() -> {
			customers.save(new Customer("Eve Again", "eve@example.com", Tier.STANDARD));
			em.flush();
		}).isInstanceOf(DataIntegrityViolationException.class);
	}

}
