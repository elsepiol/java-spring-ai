-- Track 08 (JPA): the schema every JPA kata maps to. Flyway runs this on each test database.
CREATE TABLE jpa_customer (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name   text        NOT NULL,
    email       text        NOT NULL UNIQUE,
    tier        text        NOT NULL CHECK (tier IN ('STANDARD', 'GOLD')),
    created_at  timestamptz NOT NULL
);
CREATE TABLE jpa_purchase_order (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id  bigint NOT NULL REFERENCES jpa_customer (id),
    total_cents  bigint NOT NULL
);
CREATE TABLE jpa_product (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku          text   NOT NULL UNIQUE,
    name         text   NOT NULL,
    category     text   NOT NULL,
    price_cents  bigint NOT NULL,
    version      int    NOT NULL DEFAULT 0
);
CREATE TABLE jpa_order_header (
    id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer  text NOT NULL
);
CREATE TABLE jpa_order_item (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id          bigint NOT NULL REFERENCES jpa_order_header (id),
    sku               text   NOT NULL,
    quantity          int    NOT NULL,
    unit_price_cents  bigint NOT NULL
);
CREATE INDEX ON jpa_order_item (order_id);
CREATE TABLE jpa_category (
    id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name  text NOT NULL
);
CREATE TABLE jpa_catalog_item (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id  bigint NOT NULL REFERENCES jpa_category (id),
    name         text   NOT NULL
);
CREATE TABLE jpa_account (
    id             bigint PRIMARY KEY,
    owner          text   NOT NULL,
    balance_cents  bigint NOT NULL CHECK (balance_cents >= 0)
);
CREATE TABLE jpa_audit (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    action      text        NOT NULL,
    created_at  timestamptz NOT NULL DEFAULT now()
);
